#!/usr/bin/env node
/**
 * scripts/sync-version.mjs
 * Desktop version synchronizer. Android keeps its own Expo/package version.
 * 
 * Usage:
 *   node scripts/sync-version.mjs          # Syncs all files with version.json
 *   node scripts/sync-version.mjs 0.1.2    # Updates version.json to 0.1.2 and syncs all files
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const versionJsonPath = path.join(rootDir, 'version.json');
let versionConfig = JSON.parse(fs.readFileSync(versionJsonPath, 'utf8'));

const cliVersion = process.argv[2];
if (cliVersion && typeof cliVersion === 'string' && cliVersion.trim().length > 0) {
  const cleanVer = cliVersion.trim().replace(/^v/, '');
  console.log(`==> Updating the canonical version to: ${cleanVer}`);
  versionConfig.version = cleanVer;
  const now = new Date();
  const yyyy = now.getUTCFullYear();
  const mm = String(now.getUTCMonth() + 1).padStart(2, '0');
  const dd = String(now.getUTCDate()).padStart(2, '0');
  versionConfig.buildDate = `${yyyy}-${mm}-${dd}`;
  const buildPrefix = `${yyyy}${mm}${dd}`;
  const previousBuild = String(versionConfig.build || '');
  const previousSequence = previousBuild.startsWith(`${buildPrefix}.`)
    ? Number(previousBuild.split('.')[1]) || 0
    : 0;
  versionConfig.build = `${buildPrefix}.${previousSequence + 1}`;
  fs.writeFileSync(versionJsonPath, JSON.stringify(versionConfig, null, 2) + '\n', 'utf8');
}

const { version, build, buildDate, appName, brand, copyright, engine } = versionConfig;
const versionTag = `v${version}`;
console.log(`==> Synchronising WING CONTROLLER ${versionTag} (build ${build})...`);

// 1. Update desktop/src-tauri/tauri.conf.json
const tauriConfPath = path.join(rootDir, 'desktop', 'src-tauri', 'tauri.conf.json');
if (fs.existsSync(tauriConfPath)) {
  const tauriConf = JSON.parse(fs.readFileSync(tauriConfPath, 'utf8'));
  if (tauriConf.version !== version) {
    tauriConf.version = version;
    fs.writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2) + '\n', 'utf8');
    console.log(`  [OK] desktop/src-tauri/tauri.conf.json -> ${version}`);
  } else {
    console.log(`  [-] desktop/src-tauri/tauri.conf.json was already on ${version}`);
  }
}

// 2. Update desktop/src-tauri/Cargo.toml
const cargoTomlPath = path.join(rootDir, 'desktop', 'src-tauri', 'Cargo.toml');
if (fs.existsSync(cargoTomlPath)) {
  let cargoContent = fs.readFileSync(cargoTomlPath, 'utf8');
  const updatedCargo = cargoContent.replace(
    /^version\s*=\s*"[^"]*"/m,
    `version = "${version}"`
  );
  if (updatedCargo !== cargoContent) {
    fs.writeFileSync(cargoTomlPath, updatedCargo, 'utf8');
    console.log(`  [OK] desktop/src-tauri/Cargo.toml -> ${version}`);
  } else {
    console.log(`  [-] desktop/src-tauri/Cargo.toml was already on ${version}`);
  }
}

// 3. Generate desktop/ui/version.js
const uiVersionJsPath = path.join(rootDir, 'desktop', 'ui', 'version.js');
const versionJsContent = `// Auto-generated by scripts/sync-version.mjs - DO NOT EDIT MANUALLY
// Source of truth: version.json
window.APP_VERSION_INFO = {
  version: "${version}",
  tag: "${versionTag}",
  build: "${build}",
  buildDate: "${buildDate}",
  appName: "${appName}",
  brand: "${brand}",
  copyright: "${copyright}",
  fullTitle: "${appName} ${versionTag} · ${brand}",
  engine: "${engine} ${versionTag}"
};
`;
fs.writeFileSync(uiVersionJsPath, versionJsContent, 'utf8');
console.log(`  [OK] desktop/ui/version.js generated.`);

console.log(`==> Version synchronisation complete for ${versionTag}!`);
